from pathlib import Path
import joblib
import pandas as pd
import streamlit as st

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "student_performance_model.joblib"

st.set_page_config(
    page_title="Student Performance Prediction",
    page_icon="🎓",
    layout="wide"
)

@st.cache_resource
def load_bundle():
    if not MODEL_PATH.exists():
        return None
    return joblib.load(MODEL_PATH)

bundle = load_bundle()

st.title("🎓 Student Performance Prediction")
st.write(
    "Predict a student's estimated final grade (G3, out of 20) "
    "from demographic, family, social and educational characteristics."
)

if bundle is None:
    st.error("The trained model file was not found.")
    st.code("python train_model.py\npython -m streamlit run app.py", language="bash")
    st.stop()

st.caption(f"Model: {bundle['model_name']}")

feature_columns = bundle["feature_columns"]
categorical_cols = bundle["categorical_cols"]
numerical_cols = bundle["numerical_cols"]

with st.form("student_details"):
    st.subheader("Enter student details")
    input_data = {}
    left, right = st.columns(2)

    for i, feature in enumerate(feature_columns):
        area = left if i % 2 == 0 else right
        label = feature.replace("_", " ").title()

        with area:
            if feature in categorical_cols:
                options = bundle["categorical_options"].get(feature, [])
                default = bundle["categorical_defaults"].get(feature)
                if not options:
                    st.warning(f"No known values available for {label}.")
                    continue
                default_index = options.index(default) if default in options else 0
                input_data[feature] = st.selectbox(
                    label,
                    options=options,
                    index=default_index,
                    key=f"cat_{feature}"
                )
            elif feature in numerical_cols:
                info = bundle["numerical_defaults"][feature]
                minimum = info["min"]
                maximum = info["max"]
                default = min(max(info["median"], minimum), maximum)
                step = 1.0 if info["integer"] else 0.1
                input_data[feature] = st.number_input(
                    label,
                    min_value=minimum,
                    max_value=maximum,
                    value=default,
                    step=step,
                    key=f"num_{feature}"
                )

    submitted = st.form_submit_button("Predict Final Grade", type="primary")

if submitted:
    try:
        row = {col: input_data[col] for col in feature_columns}
        input_df = pd.DataFrame([row], columns=feature_columns)
        prediction = float(bundle["model"].predict(input_df)[0])

        # Keep displayed output within the dataset's target range.
        low = bundle.get("target_min", 0.0)
        high = bundle.get("target_max", 20.0)
        prediction_display = min(max(prediction, low), high)

        st.subheader("Prediction")
        st.metric("Estimated final grade (G3)", f"{prediction_display:.2f} / 20")

        if prediction_display >= 16:
            st.success("Estimated category: High")
        elif prediction_display >= 10:
            st.info("Estimated category: Moderate")
        else:
            st.warning("Estimated category: Low")

        st.caption(
            "This is an estimate generated by a machine learning model, "
            "not a guaranteed result or a formal assessment of a student."
        )
    except Exception as exc:
        st.error(f"Prediction failed: {exc}")
